#!/usr/bin/env python3
"""Set the display width of every screenshot figure in the user guide pages.

Screenshots are captured at 2x device pixel ratio, and GitBook shows an image
at its natural pixel width up to the column width, so without an explicit
width every crop renders twice as large as the real UI. This script reads
each styled image's pixel size and writes `width="<pixels / scale>"` on the
matching `<img>` tag, so the image displays at its real size and stays crisp
on high-density screens. Full-width shots keep their width too; the column
caps them.

Usage: python3 apply_widths.py <docs-repo-root> [--scale 2] [--max-height 640]

--max-height scales tall images down further so that their displayed height
does not exceed the given CSS pixels (0 disables the cap).
"""
import argparse
import os
import re
import sys

from PIL import Image

# Only screenshots generated by this pipeline, which live in a per-page
# subfolder of .gitbook/assets. The legacy images sit flat in .gitbook/assets
# and were captured at 1x, so their widths must not be halved.
IMG_RE = re.compile(r'<img\s+src="([^"]+\.gitbook/assets/[^/"]+/[^"]+\.png)"([^>]*)>')


def display_width(path, scale, max_height):
    with Image.open(path) as im:
        w, h = im.size
    width = w / scale
    height = h / scale
    if max_height and height > max_height:
        width = width * max_height / height
    return int(round(width))


def process_page(page_path, scale, max_height, dry_run):
    text = open(page_path, encoding="utf-8").read()
    page_dir = os.path.dirname(page_path)
    changes = 0

    def repl(match):
        nonlocal changes
        src, rest = match.group(1), match.group(2)
        abs_path = os.path.normpath(os.path.join(page_dir, src))
        if not os.path.exists(abs_path):
            return match.group(0)
        width = display_width(abs_path, scale, max_height)
        rest_clean = re.sub(r'\s+width="[^"]*"', "", rest)
        new = f'<img src="{src}"{rest_clean} width="{width}">'
        if new != match.group(0):
            changes += 1
        return new

    new_text = IMG_RE.sub(repl, text)
    if changes and not dry_run:
        open(page_path, "w", encoding="utf-8").write(new_text)
    return changes


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("repo_root")
    ap.add_argument("--scale", type=float, default=2.0)
    ap.add_argument("--max-height", type=int, default=640)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    total = 0
    for root, _dirs, files in os.walk(os.path.join(args.repo_root, "superdesk-user-guide")):
        for name in files:
            if name.endswith(".md"):
                path = os.path.join(root, name)
                n = process_page(path, args.scale, args.max_height, args.dry_run)
                if n:
                    print(f"{n:3} width(s) set in {os.path.relpath(path, args.repo_root)}")
                    total += n
    print(f"{total} image tag(s) updated{' (dry run)' if args.dry_run else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
